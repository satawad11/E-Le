<?php

namespace App\Services;

use Illuminate\Support\Carbon;

/**
 * เวลาอ้างอิงที่เชื่อถือได้ (SoT §10 · INT-04)
 *
 * งานสารบรรณผูกผลทางกฎหมายไว้กับเวลา — วันที่รับหนังสือ เวลาที่ประทับตรารับ
 * และเวลาที่ลงนาม ล้วนเป็นหลักฐาน ถ้าโค้ดกระจายกันเรียก `now()` เอง จะไม่มีจุดใด
 * ที่เปลี่ยนไปใช้แหล่งเวลาที่รับรอง (NTP ที่ลงลายเซ็น หรือ TSA) ได้ในภายหลัง
 * โดยไม่ต้องไล่แก้ทั้งระบบ
 *
 * ตอนนี้ยังใช้นาฬิกาของเครื่องเป็นแหล่งเวลา — สิ่งที่คลาสนี้ให้ตั้งแต่วันแรกคือ
 * **ตะเข็บเดียว** ที่จะเปลี่ยนแหล่งเวลาได้ทีหลัง และเป็นจุดเดียวที่ชุดทดสอบ
 * ตรึงเวลาได้โดยไม่ต้องแตะนาฬิกาส่วนกลางของทั้งแอป
 *
 * `SarabanCoreContractTest` บังคับว่าโดเมนของสารบรรณต้องเรียกผ่านที่นี่
 * ห้ามเรียก `now()` / `Carbon::now()` ตรง ๆ
 */
class TrustedClock
{
    /** เวลาที่ตรึงไว้สำหรับชุดทดสอบ — `null` = ใช้นาฬิกาจริง */
    private static ?Carbon $frozenAt = null;

    /** เวลาปัจจุบันตามแหล่งเวลาที่ระบบเชื่อถือ */
    public function now(): Carbon
    {
        return self::$frozenAt?->copy() ?? Carbon::now();
    }

    /** วันที่ปัจจุบันในรูปแบบ Y-m-d — ใช้เทียบช่วงเวลามีผลของตำแหน่ง/การมอบอำนาจ */
    public function today(): string
    {
        return $this->now()->toDateString();
    }

    /**
     * ตรึงเวลาไว้ที่จุดหนึ่ง (ใช้ในชุดทดสอบเท่านั้น)
     *
     * แยกจาก `Carbon::setTestNow()` โดยตั้งใจ เพื่อให้ทดสอบพฤติกรรมที่ผูกกับ
     * เวลาอ้างอิงของสารบรรณได้ โดยไม่กระทบ `created_at` ของทั้งระบบ
     */
    public static function freeze(Carbon $at): void
    {
        self::$frozenAt = $at;
    }

    public static function release(): void
    {
        self::$frozenAt = null;
    }
}
