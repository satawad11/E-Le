<?php

return [
    /*
     * สวิตช์ฉุกเฉินของ Document Engine ทั้งระบบ (ค่าเริ่มต้น: เปิด)
     *
     * การใช้แบบฟอร์มที่ออกแบบเปิด/ปิดรายประเภทการลาได้จากหน้า "แบบฟอร์มใบลา" ในศูนย์จัดการเอกสาร
     * ประเภทที่ยังไม่เปิดใช้งานเดินเส้นทางเดิม (dompdf + blade) เหมือนก่อนมี engine ทุกประการ
     * ตั้ง false = ทุกประเภทกลับไปเส้นทางเดิมทันทีโดยไม่ต้อง deploy
     */
    'enabled' => (bool) env('DOCUMENT_ENGINE_ENABLED', true),

    /*
     * การตั้งค่าแบบเดิม: บังคับใช้ engine กับประเภทการลาที่ระบุ (นอกเหนือจากสวิตช์ในหน้าผู้ดูแล)
     *
     *   'leave_types' => [1, 5]   บังคับเฉพาะ leave type id ที่ระบุ
     *   'leave_types' => ['*']    บังคับทุกประเภท
     *   'leave_types' => []       ใช้สวิตช์ในหน้าผู้ดูแลอย่างเดียว (ค่าเริ่มต้น)
     */
    'entities' => [
        'leave_types' => array_values(array_filter(array_map(
            'trim',
            explode(',', (string) env('DOCUMENT_ENGINE_LEAVE_TYPES', '')),
        ))),
    ],

    /*
     * บันทึกไฟล์เอกสารทุกครั้งที่ออกหรือไม่
     *
     * false = ออกไฟล์ให้ผู้ใช้อย่างเดียว (เบากว่า)
     * true  = เก็บทุกครั้งเป็น revision (ตรวจสอบย้อนหลังได้ละเอียดที่สุด)
     * ไม่ว่าค่าใด เอกสารของใบลาที่อนุมัติแล้วจะถูกเก็บเป็นฉบับสมบูรณ์เสมอ
     */
    'store_every_render' => (bool) env('DOCUMENT_ENGINE_STORE_EVERY_RENDER', false),
];
